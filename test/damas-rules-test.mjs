// Testes das REGRAS da damas: captura obrigatória e máxima, cadeia, dama voadora, promoção, vitória.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { estadoInicial, movimentosLegais, aplicar, estadoJogo, escura, corDe } from '../js/damas-rules.js';

function tab(s) {
  // monta o tabuleiro: linhas de 8 chars de CIMA para baixo (a 1ª = rank 8); w/b/D/P, . vazio
  const map = { w: 'wP', W: 'wD', b: 'bP', B: 'bD' };
  const linhas = s.split('\n').map(l => l.trim()).filter(Boolean);
  assert.equal(linhas.length, 8, '8 linhas');
  const t = new Array(64).fill(null);
  for (let rIdx = 0; rIdx < 8; rIdx++) {
    const rank = 7 - rIdx;
    for (let f = 0; f < 8; f++) {
      const ch = linhas[rIdx][f];
      if (ch !== '.') t[rank * 8 + f] = map[ch] || null;
    }
  }
  return t;
}
const estadoDe = (s, turno = 'w') => ({ tabuleiro: tab(s), turno });

test('posição inicial: 24 peças (12 por lado), só em casas escuras', () => {
  const s = estadoInicial();
  const brancas = s.tabuleiro.filter(p => p && corDe(p) === 'w').length;
  const pretas = s.tabuleiro.filter(p => p && corDe(p) === 'b').length;
  assert.equal(brancas, 12);
  assert.equal(pretas, 12);
  assert.ok(s.tabuleiro.every((p, i) => !p || escura(i)), 'todas em casas escuras');
});

test('peão anda só na diagonal para frente (1 casa)', () => {
  const s = estadoDe(`
........
........
........
........
........
.w.w....
........
........`, 'w');
  const legal = movimentosLegais(s);
  // sem peças adversárias perto: 4 lances diagonais simples para cima
  assert.equal(legal.length, 4, `4 lances diagonais (foram ${legal.length})`);
  assert.ok(legal.every(m => m.capturas.length === 0), 'sem capturas');
  assert.ok(legal.every(m => m.to === m.from + 7 || m.to === m.from + 9), 'para frente (rank +1)');
});

test('captura é obrigatória: com captura disponível, só capturas são legais', () => {
  const s = estadoDe(`
........
........
........
...b....
....w...
........
........
........`, 'w');
  // peão branco e4: o peão preto em d5 está na diagonal → captura obrigatória
  const legal = movimentosLegais(s);
  assert.ok(legal.length > 0, 'lances legais');
  assert.ok(legal.every(m => m.capturas.length > 0), 'só capturas quando há captura');
});

test('captura simples: pula a peça adjacente e pousa além', () => {
  const s = estadoDe(`
........
........
........
...b....
....w...
........
........
........`, 'w');
  const legal = movimentosLegais(s);
  const cap = legal.find(m => m.capturas.length === 1);
  assert.ok(cap, 'captura disponível');
  const novo = aplicar(s, cap);
  assert.equal(novo.tabuleiro[cap.capturas[0]], null, 'a peça capturada some');
  assert.equal(novo.tabuleiro[cap.to], 'wP', 'o peão pousou além');
});

test('cadeia de captura dupla: a mesma peça captura 2 e promove ao terminar na última fileira', () => {
  const s = estadoDe(`
........
..b.....
........
..b.....
...w....
........
........
........`, 'w');
  // peão branco d4: captura c5 → pousa b6 → captura c7 → pousa d8 (e vira DAMA)
  const legal = movimentosLegais(s);
  const dupla = legal.find(m => m.capturas.length === 2);
  assert.ok(dupla, 'a cadeia dupla é o único lance legal (captura máxima)');
  assert.ok(legal.every(m => m.capturas.length === 2), 'só a captura máxima');
  const novo = aplicar(s, dupla);
  for (const c of dupla.capturas) assert.equal(novo.tabuleiro[c], null, 'as duas capturas somem');
  assert.equal(novo.tabuleiro[dupla.to], 'wD', 'terminou na última fileira → vira dama');
});

test('captura máxima obrigatória: com 1 e 2 capturas disponíveis, só as duplas são legais', () => {
  const s = estadoDe(`
.b..b...
........
........
.w......
....w...
........
........
........`, 'w');
  const legal = movimentosLegais(s);
  assert.ok(legal.length > 0);
  const max = Math.max(...legal.map(m => m.capturas.length));
  assert.ok(legal.every(m => m.capturas.length === max), `só capturas máximas (max=${max})`);
});

test('promoção: peão chegando à última fileira vira dama', () => {
  const s = estadoDe(`
........
......w.
........
........
........
........
........
........`, 'w');
  const legal = movimentosLegais(s);
  assert.ok(legal.length >= 1);
  const m = legal[0];
  const novo = aplicar(s, m);
  // o peão (rank 7) andando para rank 8 vira dama
  if (Math.floor(m.to / 8) === 7) {
    assert.equal(novo.tabuleiro[m.to], 'wD', 'vira dama');
  }
});

test('dama voadora: anda qualquer distância na diagonal', () => {
  const s = estadoDe(`
........
........
.W......
........
........
........
........
......b.`, 'w');
  const legal = movimentosLegais(s);
  const longos = legal.filter(m => Math.abs(m.to - m.from) > 9);
  assert.ok(longos.length > 0, `a dama anda longe (lances: ${legal.length})`);
});

test('dama captura voadora: pula a vítima com casas vazias antes/depois', () => {
  const s = estadoDe(`
........
........
.W......
........
........
....b...
........
........`, 'w');
  // dama branca (c6): voa pela diagonal, pula o peão preto (e4) e pousa além
  const legal = movimentosLegais(s);
  const cap = legal.find(m => m.capturas.length === 1);
  assert.ok(cap, 'captura da dama disponível');
  assert.ok(Math.abs(cap.to - cap.capturas[0]) > 9 || Math.abs(cap.to - cap.from) > 9, 'pousa além da vítima');
});

test('vitória: sem peças ou sem lances = quem tem a vez perdeu', () => {
  const s = estadoDe(`
........
........
........
........
........
........
........
.......w`, 'b');
  // o preto não tem peças → vitoria (o preto perdeu)
  assert.equal(estadoJogo(s), 'vitoria');
  const s2 = estadoDe(`
........
........
........
........
........
.W.w.W.w
..b.....
........`, 'b');
  // o peão preto preso (brancos em cima e nas diagonais): sem lances → vitoria
  if (movimentosLegais(s2).length === 0) assert.equal(estadoJogo(s2), 'vitoria');
});

test('o turno inverte após cada lance', () => {
  const s = estadoInicial();
  const legal = movimentosLegais(s);
  const novo = aplicar(s, legal[0]);
  assert.equal(novo.turno, 'b', 'branco jogou → preto');
});
